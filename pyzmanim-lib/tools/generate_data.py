"""
Generator script: parses the vendored VBA source in reference/vbzmanim and
auto-generates the pure-data Python modules under pyzmanim/_data/.

Rationale: mod_shiur.bas / mod_dafyomi.bas / mod_parasha.bas / mod_hdateformat.bas
contain thousands of lines of Hebrew-text lookup tables. Hand-retyping this text
would be slow and error-prone (religious text accuracy matters). Instead we parse
the original VBA assignments directly with regex, which guarantees byte-for-byte
fidelity with upstream and lets us re-run this script whenever
https://github.com/diaphone1/vbzmanim is updated.

Usage:
    python tools/generate_data.py

Requires the reference/vbzmanim folder to exist (see reference/vbzmanim/README.md
for provenance). Files there were re-encoded from Windows-1255 to UTF-8.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "reference" / "vbzmanim"
OUT = ROOT / "pyzmanim" / "_data"

HEADER = '''"""
AUTO-GENERATED FILE - do not edit by hand.

Generated by tools/generate_data.py from the original VBA source at
https://github.com/diaphone1/vbzmanim (vendored under reference/vbzmanim/).
Re-run tools/generate_data.py to regenerate after pulling upstream changes.
"""
'''

ASSIGN_1D_RE = re.compile(
    r'^\s*(\w+)\(\s*(\d+)\s*\)\s*=\s*"((?:[^"]|"")*)"'
)
ASSIGN_2D_RE = re.compile(
    r'^\s*(\w+)\(\s*(\d+)\s*,\s*(\d+)\s*\)\s*=\s*"((?:[^"]|"")*)"'
)
ASSIGN_2D_ENUM_RE = re.compile(
    r'^\s*(\w+)\(\s*(\d+)\s*,\s*(\d+)\s*\)\s*=\s*(\w+)\s*$'
)


def unescape_vba_string(s: str) -> str:
    return s.replace('""', '"')


def parse_1d_arrays(text: str, names: list[str]) -> dict[str, dict[int, str]]:
    result: dict[str, dict[int, str]] = {name: {} for name in names}
    for line in text.splitlines():
        m = ASSIGN_1D_RE.match(line)
        if not m:
            continue
        name, idx, value = m.group(1), int(m.group(2)), m.group(3)
        if name in result:
            result[name][idx] = unescape_vba_string(value)
    return result


def parse_2d_string_array(text: str, name: str) -> dict[tuple[int, int], str]:
    result: dict[tuple[int, int], str] = {}
    for line in text.splitlines():
        m = ASSIGN_2D_RE.match(line)
        if not m or m.group(1) != name:
            continue
        row, col, value = int(m.group(2)), int(m.group(3)), m.group(4)
        result[(row, col)] = unescape_vba_string(value)
    return result


def parse_2d_enum_array(text: str, name: str) -> dict[tuple[int, int], str]:
    result: dict[tuple[int, int], str] = {}
    for line in text.splitlines():
        m = ASSIGN_2D_ENUM_RE.match(line)
        if not m or m.group(1) != name:
            continue
        row, col, value = int(m.group(2)), int(m.group(3)), m.group(4)
        result[(row, col)] = value
    return result


def dict_to_list(d: dict[int, str], size: int, default: str = "") -> list[str]:
    return [d.get(i, default) for i in range(size)]


def emit_list_literal(varname: str, values: list[str], out_lines: list[str]) -> None:
    out_lines.append(f"{varname} = [")
    for v in values:
        out_lines.append(f"    {v!r},")
    out_lines.append("]")
    out_lines.append("")


def emit_grid_literal(
    varname: str,
    grid: dict[tuple[int, int], str],
    rows: int,
    cols: int,
    default: str = "",
    out_lines: list[str] | None = None,
) -> None:
    assert out_lines is not None
    out_lines.append(f"{varname} = [")
    for r in range(rows):
        row_values = [grid.get((r, c), default) for c in range(cols)]
        out_lines.append(f"    {row_values!r},")
    out_lines.append("]")
    out_lines.append("")


# ---------------------------------------------------------------------------
# mod_parasha.bas -> parasha_data.py  (17 x 56 grid of Parshah enum-name strings)
# ---------------------------------------------------------------------------
def generate_parasha_data() -> None:
    text = (REF / "mod_parasha.bas").read_text(encoding="utf-8")
    grid = parse_2d_enum_array(text, "parashaList")
    max_row = max(r for r, _ in grid) + 1
    max_col = max(c for _, c in grid) + 1
    out: list[str] = [HEADER, ""]
    emit_grid_literal(
        "PARASHA_LIST", grid, max_row, max_col, default="NOPARSHAH", out_lines=out
    )
    (OUT / "parasha_data.py").write_text("\n".join(out), encoding="utf-8")
    print(f"parasha_data.py: {max_row}x{max_col} grid")


