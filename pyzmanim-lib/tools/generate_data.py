# mod_dafyomi.bas -> dafyomi_data.py
# ---------------------------------------------------------------------------
def generate_dafyomi_data() -> None:
    text = (REF / "mod_dafyomi.bas").read_text(encoding="utf-8")
    names = [
        "mishnayos_arr", "masechtosBavli", "masechtosBavliTransliterated",
        "masechtosYerushalmi", "masechtosYerushalmiTransliterated",
    ]
    arrays = parse_1d_arrays(text, names)
    # numeric arrays (blattPerMasechta / blattPerMasechtaYerushalmi) aren't
    # strings; parse them separately.
    blatt_re = re.compile(r'^\s*(blattPerMasechta|blattPerMasechtaYerushalmi)\((\d+)\)\s*=\s*(\d+)\s*$')
    blatt: dict[str, dict[int, int]] = {"blattPerMasechta": {}, "blattPerMasechtaYerushalmi": {}}
    for line in text.splitlines():
        m = blatt_re.match(line)
        if m:
            blatt[m.group(1)][int(m.group(2))] = int(m.group(3))

    out: list[str] = [HEADER, ""]
    emit_list_literal("MISHNAYOS_ARR", dict_to_list(arrays["mishnayos_arr"], 64), out)
    emit_list_literal("MASECHTOS_BAVLI", dict_to_list(arrays["masechtosBavli"], 40), out)
    emit_list_literal(
        "MASECHTOS_BAVLI_TRANSLITERATED",
        dict_to_list(arrays["masechtosBavliTransliterated"], 40), out,
    )
    emit_list_literal("MASECHTOS_YERUSHALMI", dict_to_list(arrays["masechtosYerushalmi"], 39), out)
    emit_list_literal(
        "MASECHTOS_YERUSHALMI_TRANSLITERATED",
        dict_to_list(arrays["masechtosYerushalmiTransliterated"], 39), out,
    )
    blatt_list = [blatt["blattPerMasechta"].get(i, 0) for i in range(40)]
    out.append(f"BLATT_PER_MASECHTA = {blatt_list!r}")
    out.append("")
    blatt_y_list = [blatt["blattPerMasechtaYerushalmi"].get(i, 0) for i in range(39)]
    out.append(f"BLATT_PER_MASECHTA_YERUSHALMI = {blatt_y_list!r}")
    out.append("")
    (OUT / "dafyomi_data.py").write_text("\n".join(out), encoding="utf-8")
    print("dafyomi_data.py generated")


# ---------------------------------------------------------------------------
# mod_shiur.bas -> shiur_data.py
# ---------------------------------------------------------------------------
def generate_shiur_data() -> None:
    text = (REF / "mod_shiur.bas").read_text(encoding="utf-8")
    names = ["TehillimArray", "halachayomi"]
    arrays = parse_1d_arrays(text, names)
    tehillim = dict_to_list(arrays["TehillimArray"], 31)
    halacha = dict_to_list(arrays["halachayomi"], 404)

    # rambamarray3chp / rambamarray1chp can contain very large indices; find max dynamically
    def parse_1d_dynamic(name: str) -> dict[int, str]:
        pattern = re.compile(rf'^\s*{name}\(\s*(\d+)\s*\)\s*=\s*"((?:[^"]|"")*)"')
        result: dict[int, str] = {}
        for line in text.splitlines():
            m = pattern.match(line)
            if m:
                result[int(m.group(1))] = unescape_vba_string(m.group(2))
        return result

    rambam3 = parse_1d_dynamic("rambamarray3chp")
    rambam1 = parse_1d_dynamic("rambamarray1chp")
    rambam3_list = dict_to_list(rambam3, max(rambam3) + 1)
    rambam1_list = dict_to_list(rambam1, max(rambam1) + 1)

    tanya_regular = parse_2d_string_array(text, "tanyaarrayregular")
    tanya_leap = parse_2d_string_array(text, "tanyaarrayleap")

    out: list[str] = [HEADER, ""]
    emit_list_literal("TEHILLIM_ARRAY", tehillim, out)
    emit_list_literal("HALACHA_YOMI", halacha, out)
    emit_list_literal("RAMBAM_3CHP", rambam3_list, out)
    emit_list_literal("RAMBAM_1CHP", rambam1_list, out)
    emit_grid_literal("TANYA_REGULAR", tanya_regular, 13, 32, out_lines=out)
    emit_grid_literal("TANYA_LEAP", tanya_leap, 14, 32, out_lines=out)
    (OUT / "shiur_data.py").write_text("\n".join(out), encoding="utf-8")
    print(
        f"shiur_data.py: tehillim={len(tehillim)} halacha={len(halacha)} "
        f"rambam3={len(rambam3_list)} rambam1={len(rambam1_list)}"
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    init_file = OUT / "__init__.py"
    if not init_file.exists():
        init_file.write_text("", encoding="utf-8")
    generate_parasha_data()
    generate_hdateformat_data()
    generate_dafyomi_data()
    generate_shiur_data()


if __name__ == "__main__":
    main()
