CASE_LINE_RE = re.compile(r'^\s*Case\s+(.+?):?\s*$')
FORMAT_LINE_RE = re.compile(r'^\s*YomTovFormat\s*=\s*"((?:[^"]|"")*)"\s*$')


def expand_case_targets(case_expr: str) -> list[str]:
    """Expand a VBA `Case A, B, C To D` expression into enum name list."""
    targets: list[str] = []
    for part in case_expr.split(","):
        part = part.strip()
        if " To " in part:
            start_name, end_name = [p.strip() for p in part.split(" To ")]
            start_i = YOMTOV_ORDER.index(start_name)
            end_i = YOMTOV_ORDER.index(end_name)
            targets.extend(YOMTOV_ORDER[start_i:end_i + 1])
        else:
            targets.append(part)
    return targets


def parse_yomtov_format(text: str) -> dict[str, str]:
    lines = text.splitlines()
    in_func = False
    result: dict[str, str] = {}
    pending_targets: list[str] = []
    for line in lines:
        if "Function YomTovFormat" in line:
            in_func = True
            continue
        if not in_func:
            continue
        if line.strip().startswith("End Function"):
            break
        case_m = CASE_LINE_RE.match(line)
        if case_m and not line.strip().startswith("Case Else"):
            pending_targets = expand_case_targets(case_m.group(1))
            continue
        if line.strip().startswith("Case Else"):
            pending_targets = []
            continue
        fmt_m = FORMAT_LINE_RE.match(line)
        if fmt_m and pending_targets:
            value = unescape_vba_string(fmt_m.group(1))
            for t in pending_targets:
                result[t] = value
            pending_targets = []
    return result


def generate_hdateformat_data() -> None:
    text = (REF / "mod_hdateformat.bas").read_text(encoding="utf-8")
    arrays = parse_1d_arrays(text, ["hchar", "hmonth", "hwday", "parshahchar"])
    hchar = dict_to_list(arrays["hchar"], 25, default="?")
    hmonth = dict_to_list(arrays["hmonth"], 14)
    hwday = dict_to_list(arrays["hwday"], 8)
    parshahchar = dict_to_list(arrays["parshahchar"], 62)
    yomtov_format = parse_yomtov_format(text)

    out: list[str] = [HEADER, ""]
    emit_list_literal("HCHAR", hchar, out)
    emit_list_literal("HMONTH", hmonth, out)
    emit_list_literal("HWDAY", hwday, out)
    emit_list_literal("PARSHAHCHAR", parshahchar, out)
    out.append("YOMTOV_FORMAT = {")
    for k, v in yomtov_format.items():
        out.append(f"    {k!r}: {v!r},")
    out.append("}")
    out.append("")
    (OUT / "hdateformat_data.py").write_text("\n".join(out), encoding="utf-8")
    print(f"hdateformat_data.py: {len(yomtov_format)} yomtov format entries")


